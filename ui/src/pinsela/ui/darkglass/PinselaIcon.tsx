export type PinselaIconName = keyof typeof ICONS;

export interface PinselaIconProps extends React.SVGProps<SVGSVGElement> {
  name: string;
  size?: number | string;
  strokeWidth?: number;
  className?: string;
}

export const PinselaIcon: React.FC<PinselaIconProps> = ({
  name,
  size = 18,
  strokeWidth = 1.75,
  className = "",
  ...rest
}) => {
  const IconComponent = ICONS[name as PinselaIconName];

  if (!IconComponent) {
    console.warn(`Icon "${name}" not found in lucide-react.`);
    return null;
  }

  return (
    <IconComponent
      size={Number(size) || 18}
      strokeWidth={Number(strokeWidth) || 1.75}
      className={`dg-pinsela-icon ${className}`}
      {...rest}
    />
  );
};
